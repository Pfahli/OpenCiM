#!/usr/bin/env node
// gen-port-operators - generate the ReGS operator dispatch table from docs/script-runtime/operators.json.
// Output: a C++ include with one enum value per engine handler (named after its address) and the table
// kOpTable[op][leftCat][rightCat] -> handler (0 = not defined -> "Operator %d not defined for operands!").
// Categories: 0 unset/macro, 1 bool, 2 int, 3 float, 4 string, 5 null/object, 6 array, 7 function, 8 event, 9 map,
// 10 vector, 11 quaternion.
//
// Usage: node gen-port-operators.mjs <operators.json> <out.inc>

import fs from 'node:fs';

const [inFile, outFile] = process.argv.slice(2);
const j = JSON.parse(fs.readFileSync(inFile, 'utf8'));
const handlers = Object.keys(j.handlers).sort();
const id = new Map(handlers.map((h, i) => [h, i + 1]));
const table = Array.from({ length: 0x2c }, () => Array.from({ length: 12 }, () => new Array(12).fill(0)));
for (const c of j.cells) {
  const op = parseInt(c.op, 16);
  table[op][c.left][c.right] = id.get(c.handler);
}
const lines = [];
lines.push('// Generated by tools/gen-port-operators.mjs from docs/script-runtime/operators.json. Do not edit.');
lines.push('// Handler ids are named after the engine function that implements them (GSystem.dll).');
lines.push('enum OpHandler : uint8_t {');
lines.push('  H_NONE = 0,');
for (const h of handlers) lines.push(`  H_${h.slice(2)} = ${id.get(h)},  // ${j.handlers[h].semantics.replace(/\s+/g, ' ').slice(0, 110)}`);
lines.push('};');
lines.push('');
lines.push('static const uint8_t kOpTable[0x2C][12][12] = {');
for (let op = 0; op < 0x2c; ++op) {
  lines.push(`  {  // op 0x${op.toString(16).padStart(2, '0')}`);
  for (let l = 0; l < 12; ++l) lines.push(`    {${table[op][l].join(', ')}},`);
  lines.push('  },');
}
lines.push('};');
fs.writeFileSync(outFile, lines.join('\n') + '\n');
console.log(`handlers ${handlers.length}, cells ${j.cells.length}`);
