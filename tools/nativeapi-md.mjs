#!/usr/bin/env node
// nativeapi-md - render docs/native-api.json (from nativeapi.mjs) and docs/rtti-classes.json as Markdown.
// Usage: node nativeapi-md.mjs <native-api.json> <rtti-classes.json> <out.md>

import fs from 'node:fs';

const [apiFile, rttiFile, out] = process.argv.slice(2);
const api = JSON.parse(fs.readFileSync(apiFile, 'utf8'));
const rtti = JSON.parse(fs.readFileSync(rttiFile, 'utf8'));
const byName = new Map(rtti.map((c) => [c.name, c]));
const INFERRED_CTORS = { new_window: 'gsWindow_OGL (inferred)', new_textControl: 'gsTextSelCtrl (inferred)' };
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const L = [];

const fns = api.globals.filter((g) => g.kind === 'function');
const consts = api.globals.filter((g) => g.kind === 'constant');
const members = api.classes.flatMap((c) => c.members);

L.push('# GSystem native scripting API', '');
L.push('Generated by `tools/nativeapi.mjs` + `tools/nativeapi-md.mjs` from the Ghidra v2 pseudocode of `GSystem.dll`');
L.push('(Cities in Motion 1.0.22) and its MSVC RTTI (`tools/rtti.mjs`). Machine-readable data: `docs/native-api.json`,');
L.push('`docs/rtti-classes.json`. Handler/registrar addresses point into `decompiled/GSystem-v2/functions/0x<addr>.c`.', '');
L.push('## How the engine exposes things to scripts', '');
L.push('* **Globals** are inserted into one name→variant map (`FUN_1000f5f0`). Functions are `gsOpaqueFunction` /');
L.push('  `gsTransparentFunction` objects holding a C handler and an argument range; constants are value variants.');
L.push('* **Class members** are declared by each class\'s virtual `registerMembers()` (vtable slot 30, offset `0x78`), run once');
L.push('  per class by `FUN_1001c2a0`, which first calls the parent class\'s registrar. Fields bind directly to an object offset');
L.push('  (`gs*FieldVariant`); methods carry a handler and argument range; events are slots scripts bind with `event obj.x::(...)`.');
L.push('* Field types (registrar → type code): bool 2 (`FUN_1001bff0`), int 3 (`FUN_1001c020`), float 4 (`FUN_1001c050`),');
L.push('  str 5 (`FUN_1001c080`), wstr 6 (`FUN_1001c0b0`), custom 7 (`FUN_1001c0e0`), var 8 (`FUN_1001c120`), bit 9 (`FUN_1001c160`);');
L.push('  methods `FUN_1001c1a0`, events `FUN_1001c200`. Every script object also has `gsObjectVariant`\'s built-ins.');
L.push('* Field callbacks (descriptor `+0x10` / `+0xc`, built by `FUN_1001bf50`): a **setter** replaces the plain store; the');
L.push('  setter `FUN_1001bfc0` throws, which marks the field **read-only** (*ro*); a **hook** is called by the default store');
L.push('  path (`FUN_1001cc40`) before the value is assigned. In the tables: `set=` setter, `hook=` hook.', '');
L.push('## Coverage', '');
L.push(`* ${fns.length} global functions, ${consts.length} constants, ${api.classes.length} script classes with ${members.length} members`);
L.push(`  (${members.filter((m) => m.kind === 'field').length} fields, ${members.filter((m) => m.kind === 'method').length} methods, ${members.filter((m) => m.kind === 'event').length} events).`);
L.push('* Cross-checked against identifiers used by the 3 601 shipped scripts: every native global function, constant and');
L.push('  member they use is present here (the usage scan\'s only misses were false positives such as `unlock`/`dds`, which are');
L.push('  script-defined).');
L.push('* Not covered: argument *types* and semantics (handlers are listed, not yet read); members created dynamically at run');
L.push('  time; the exported C embedding API (`registerFunction`, `registerConstant`, … — see the main report).', '');

// ---- class hierarchy ----
L.push('## Script classes', '');
L.push('Classes with their own member registrar, most-derived first within each base chain. `uses` = occurrences in shipped scripts.', '');
const ctorOf = new Map(fns.filter((g) => g.name?.startsWith('new_')).map((g) => [g.creates, g.name]));
const sorted = [...api.classes].sort((a, b) => (a.classes[0] ?? '').localeCompare(b.classes[0] ?? ''));
L.push('| Class | Base chain (RTTI) | Constructor | Members |', '|---|---|---|---|');
for (const c of sorted) {
  const name = c.classes[0];
  const r = byName.get(name);
  L.push(`| [${name}](#${name.toLowerCase()}) | ${esc((r?.bases ?? []).join(' > ') || '—')} | ${ctorOf.get(name) ?? '—'} | ${c.members.length} |`);
}
L.push('');

// ---- globals ----
L.push('## Global functions', '');
L.push('| Name | Args | Handler | Wrapper | Builds | Uses |', '|---|---|---|---|---|---|');
for (const g of fns.sort((a, b) => a.name.localeCompare(b.name))) {
  const args = g.minArgs === g.maxArgs ? `${g.minArgs}` : `${g.minArgs}–${g.maxArgs}`;
  const builds = g.creates ?? INFERRED_CTORS[g.name] ?? '';
  L.push(`| \`${g.name}\` | ${args} | \`${g.handler}\` | ${g.wrapper.replace('gs', '').replace('Function', '')} | ${builds} | ${g.scriptUses ?? ''} |`);
}
L.push('');

// ---- constants ----
L.push('## Constants', '');
const groups = new Map();
for (const g of consts) {
  const key = String(g.name).match(/^[A-Z]+(?:_[A-Z]+)?/)?.[0] ?? 'OTHER';
  const arr = groups.get(key) ?? [];
  arr.push(g);
  groups.set(key, arr);
}
for (const [key, arr] of [...groups.entries()].sort()) {
  const vals = arr.sort((a, b) => a.name.localeCompare(b.name)).map((g) => `\`${g.name}\`=${esc(g.value)}`);
  L.push(`* **${key}** (${arr.length}): ${vals.join(', ')}`);
}
const special = api.globals.filter((g) => g.kind !== 'function' && g.kind !== 'constant');
if (special.length) L.push('', `Unresolved: ${special.map((g) => `\`${g.name || '(name from caller)'}\` in \`${g.registeredIn}\``).join(', ')} (the exported \`registerConstant\` entry point).`);
L.push('', '`MAIN` (the script root object) is registered as `null` in `0x100a16a0`/`0x100a28b0` and bound to the main object later (**inferred**).', '');

// ---- class members ----
L.push('## Class members', '');
for (const c of sorted) {
  const name = c.classes[0];
  const r = byName.get(name);
  L.push(`### ${name}`, '');
  L.push(`Registrar \`${c.registrar}\`${c.parentClass ? `, extends **${c.parentClass}**` : ''}${r?.bases?.length ? ` · RTTI: ${esc(r.bases.join(' > '))}` : ''}${c.handRead ? ' · hand-read' : ''}.`, '');
  L.push('| Member | Kind | Type / args | Offset / handler | Id | Uses |', '|---|---|---|---|---|---|');
  for (const m of c.members) {
    const ta = m.kind === 'field' ? m.type : m.kind === 'method' ? (m.minArgs === m.maxArgs ? `${m.minArgs} args` : `${m.minArgs}–${m.maxArgs} args`) : '';
    const cb = m.kind === 'field' ? [m.readOnly ? 'ro' : '', m.setter ? `set=\`${m.setter}\`` : '', m.hook ? `hook=\`${m.hook}\`` : ''].filter(Boolean).join(' ') : '';
    const oh = m.kind === 'field' ? [m.offset ?? '', cb].filter(Boolean).join(' ') : m.kind === 'method' ? (m.handler ? `\`${m.handler}\`` : '') : '';
    L.push(`| \`${m.name}\` | ${m.kind} | ${ta} | ${oh} | ${m.id ?? ''} | ${m.scriptUses ?? ''} |`);
  }
  L.push('');
}

// ---- renderer interfaces ----
L.push('## Renderer interfaces (graphics seam)', '');
L.push('Abstract interfaces (`gsI*`) and their OpenGL implementations (`*_OGL`) from RTTI. A replacement renderer would');
L.push('implement these interfaces; `gsVideo`/`gsWindow`/post effects are the script-visible side.', '');
L.push('| Interface | Virtual methods | Implemented by |', '|---|---|---|');
for (const i of rtti.filter((c) => /^gsI[A-Z]/.test(c.name)).sort((a, b) => a.name.localeCompare(b.name))) {
  const impl = rtti.filter((c) => c.bases.includes(i.name) && c.name.endsWith('_OGL')).map((c) => c.name);
  L.push(`| ${i.name} | ${i.vtables[0].methods.length} | ${impl.join(', ') || '—'} |`);
}
L.push('');

fs.writeFileSync(out, L.join('\n'));
console.log(`wrote ${out}: ${L.length} lines`);
